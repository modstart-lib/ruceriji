// UniApp 多平台 Lucide 图标 Vite 插件
// H5:   <span v-html="...">  —— 内联 SVG，CSS currentColor / text-* 自动继承
// 非H5: <view :style="...">  —— background-image: url(data:image/svg+xml,...) URL 编码
// 用法: <icon-lucide-activity /> <icon-lucide-user :size="20" color="#ff0000" />
//
// 生成物 src/icons/lucide/ 是提交物（easycom 按文件路径解析），插件在 buildStart 自动对齐。
// 手动：node vite-plugin-uni-icons.js          补齐 / 清理生成物
//       node vite-plugin-uni-icons.js --check  只校验是否漂移，不写文件

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname)
const OUT_DIR = path.join(ROOT, 'src/icons/lucide')
const TOKEN_LESS = path.join(ROOT, 'src/config/token.less')

/**
 * 亮色主题下 `--token-*` 的实际色值。
 * 小程序端图标是 background-image: url("data:image/svg+xml,...")，
 * 独立的 SVG 文档读不到宿主页面的 CSS 变量，传 var(--token-x) 会得到无效
 * stroke（图标整个不显示），所以需要运行时查表换成具体色值。
 */
function readTokenColors() {
  if (!fs.existsSync(TOKEN_LESS)) return {}
  const less = fs.readFileSync(TOKEN_LESS, 'utf8')
  // 只取亮色主题块 `:root, page {`，暗色由 .dark 覆盖（小程序无暗色切换）
  const head = less.indexOf(':root')
  if (head < 0) return {}
  const open = less.indexOf('{', head)
  let depth = 0
  let end = less.length
  for (let i = open; i < less.length; i++) {
    if (less[i] === '{') depth++
    else if (less[i] === '}' && --depth === 0) {
      end = i
      break
    }
  }

  const raw = {}
  for (const [, name, value] of less.slice(open + 1, end).matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    raw[name] = value.trim()
  }

  // token.less 里很多变量值来自顶部的 Less 变量（@token-primary-600），一并解析
  const lessVars = {}
  for (const [, name, value] of less.matchAll(/^\s*@([\w-]+)\s*:\s*([^;]+);/gm)) {
    lessVars[name] = value.trim()
  }

  const resolve = (value, level = 0) => {
    if (level > 6) return ''
    const ref = /^var\(\s*(--[\w-]+)\s*(?:,([^)]*))?\)$/.exec(value)
    if (ref) {
      const next = raw[ref[1]]
      return (next ? resolve(next, level + 1) : '') || (ref[2] || '').trim()
    }
    const lessRef = /^@([\w-]+)$/.exec(value)
    if (lessRef) {
      const next = lessVars[lessRef[1]]
      return next ? resolve(next, level + 1) : ''
    }
    return value
  }

  const colors = {}
  for (const name of Object.keys(raw)) {
    const value = resolve(raw[name])
    // 图标只要纯色，渐变 / 阴影 / 字体等跳过
    if (/^(#[0-9a-f]{3,8}|rgba?\(|hsla?\()/i.test(value)) colors[name] = value
  }
  return colors
}

/** 生成 _token-colors.js 的源码，与磁盘内容比较后决定是否写入。 */
function buildTokenColors() {
  const colors = readTokenColors()
  const rows = Object.entries(colors)
    .map(([name, value]) => `  '${name}': '${value}',`)
    .join('\n')
  const source = `// Generated by vite-plugin-uni-icons.js — do not edit.
// Light-theme values of the design tokens: a data-URI SVG (小程序端背景图) cannot
// resolve the host page's CSS variables, so var(--token-*) is looked up here.

export const TOKEN_COLORS = {
${rows}
}

export function resolveIconColor(color) {
  const ref = /^var\\(\\s*(--[\\w-]+)\\s*(?:,([^)]*))?\\)$/.exec((color || '').trim())
  if (!ref) return color || ''
  return TOKEN_COLORS[ref[1]] || (ref[2] || '').trim()
}
`
  return { source, count: Object.keys(colors).length }
}

// IconLucideChevronRight → chevron-right
function toKebab(componentName) {
  return componentName
    .replace(/^IconLucide/, '')
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/([a-zA-Z])([0-9])/g, '$1-$2')
    .toLowerCase()
}

function getSvg(kebabName) {
  const lucide = require('@iconify-json/lucide')
  const icons = lucide.icons
  const icon = icons.icons[kebabName]
  if (!icon) return null
  const w = icons.width || 24
  const h = icons.height || 24
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${icon.body}</svg>`
}

function makeSfc(svg) {
  const svgH5 = svg.replace(/width="\d+"/, 'width="100%"').replace(/height="\d+"/, 'height="100%"')
  // 构建时预计算默认颜色 URL 编码，不依赖运行时 btoa
  const urlDefault = encodeURIComponent(svg.replace(/currentColor/g, '#333333'))
  return `<template>
  <!-- #ifdef H5 -->
  <span class="lucide-icon" v-html="_h5svg" :style="_sty" />
  <!-- #endif -->
  <!-- #ifndef H5 -->
  <view class="lucide-icon lucide-icon-mp" :style="_mpsty" />
  <!-- #endif -->
</template>
<script setup>
import { computed } from 'vue'
import { resolveIconColor } from './_token-colors.js'
const props = defineProps({
  color: { type: String, default: '' },
  size: { default: '1em' },
})
const _tpl = ${JSON.stringify(svgH5)}
const _mp = ${JSON.stringify(svg)}
const _urldef = '${urlDefault}'
const _sz = computed(() => typeof props.size === 'number' ? props.size + 'px' : props.size || '1em')
const _sty = computed(() => \`width:\${_sz.value};height:\${_sz.value}\`)
const _h5svg = computed(() => props.color ? _tpl.replace(/currentColor/g, props.color) : _tpl)
// 小程序端背景图里的 SVG 解析不了 var(--token-x)，先换算成具体色值
const _mpcolor = computed(() => resolveIconColor(props.color))
const _url = computed(() => _mpcolor.value ? encodeURIComponent(_mp.replace(/currentColor/g, _mpcolor.value)) : _urldef)
const _mpsty = computed(() => \`width:\${_sz.value};height:\${_sz.value};background-image:url("data:image/svg+xml,\${_url.value}")\`)
</script>
<style>
.lucide-icon {
  display: inline-block;
  flex-shrink: 0;
  vertical-align: middle;
  line-height: 0;
}
/* H5 内联 SVG 必须块级铺满：父容器若带 line-height（如按钮的 48px），
   inline 的 svg 会按父级行高落基线，图标整体下沉数像素 */
.lucide-icon > svg {
  display: block;
  width: 100%;
  height: 100%;
}
.lucide-icon-mp {
  background-size: contain;
  background-repeat: no-repeat;
  background-position: center;
}
</style>
`
}

function scanUsedIcons() {
  const fg = require('fast-glob')
  const vueFiles = fg.sync('src/**/*.vue', { cwd: ROOT })
  const used = new Set()
  for (const file of vueFiles) {
    const content = fs.readFileSync(path.join(ROOT, file), 'utf8')
    // kebab-case: icon-lucide-chevron-right
    for (const [, name] of content.matchAll(/\bicon-lucide-([a-z][a-z0-9-]*)/g)) {
      used.add('icon-lucide-' + name)
    }
    // PascalCase 兼容: IconLucideChevronRight → icon-lucide-chevron-right
    for (const [, suffix] of content.matchAll(/\bIconLucide([A-Za-z0-9]+)/g)) {
      used.add('icon-lucide-' + toKebab('IconLucide' + suffix))
    }
  }
  return used
}

/**
 * 期望的生成物：文件名 → 内容。图标按源码引用现算，token 色值来自 token.less，
 * 内容都是确定的，因此可以逐文件比对，只写变化的部分。
 */
function buildOutputs() {
  const { source: tokenSource, count: tokenCount } = buildTokenColors()
  const outputs = new Map([['_token-colors.js', tokenSource]])
  const unknown = []
  for (const fullName of scanUsedIcons()) {
    const svg = getSvg(fullName.replace(/^icon-lucide-/, ''))
    if (!svg) unknown.push(fullName)
    else outputs.set(fullName + '.vue', makeSfc(svg))
  }
  return { outputs, tokenCount, unknown }
}

/**
 * 让 src/icons/lucide 与源码引用保持一致：
 * 只写缺失 / 内容过期的文件，只删已无引用的旧图标，其余文件不碰（不动 mtime，构建不产生噪音）。
 * check 模式只报告不写入，返回值表示是否一致；普通模式返回 false 表示有引用找不到图标。
 */
function syncIcons({ check = false } = {}) {
  if (!check && !fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true })

  const { outputs, tokenCount, unknown } = buildOutputs()
  const existing = fs.existsSync(OUT_DIR)
    ? fs.readdirSync(OUT_DIR).filter((f) => f.endsWith('.vue'))
    : []

  const orphans = existing.filter((f) => !outputs.has(f)).sort()
  const added = []
  const changed = []
  for (const [file, content] of outputs) {
    const full = path.join(OUT_DIR, file)
    if (!fs.existsSync(full)) added.push(file)
    else if (fs.readFileSync(full, 'utf8') !== content) changed.push(file)
  }
  const iconCount = outputs.size - 1

  if (check) {
    if (orphans.length + added.length + changed.length + unknown.length === 0) {
      console.log(`[uni-icons] ${iconCount} 个图标与源码引用一致`)
      return true
    }
    console.error(
      [
        `[uni-icons] 生成物与源码引用不一致（源码引用 ${iconCount} 个图标）:`,
        ...added.map((f) => `  缺失  src/icons/lucide/${f}`),
        ...changed.map((f) => `  过期  src/icons/lucide/${f}`),
        ...orphans.map((f) => `  多余  src/icons/lucide/${f}（已无引用，需删除）`),
        ...unknown.map((f) => `  未找到 ${f}（@iconify-json/lucide 没有这个图标）`),
        '  执行 npm run icons 修复后重新提交',
      ].join('\n')
    )
    return false
  }

  for (const file of orphans) fs.unlinkSync(path.join(OUT_DIR, file))
  for (const file of [...added, ...changed]) {
    fs.writeFileSync(path.join(OUT_DIR, file), outputs.get(file), 'utf8')
  }
  if (unknown.length) {
    console.warn(`[uni-icons] 图标不存在（@iconify-json/lucide）: ${unknown.join(', ')}`)
  }
  console.log(
    `[uni-icons] ${iconCount} 个图标 / ${tokenCount} 个 token 色值 → src/icons/lucide/` +
      `（写入 ${added.length + changed.length}，删除 ${orphans.length}）`
  )
  return unknown.length === 0
}

module.exports = function vitePluginUniIcons() {
  return {
    name: 'vite-plugin-uni-icons',
    buildStart: () => {
      syncIcons()
    },
  }
}

module.exports.sync = syncIcons

if (require.main === module) {
  process.exit(syncIcons({ check: process.argv.includes('--check') }) ? 0 : 1)
}
